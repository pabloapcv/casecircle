export function growthText(lang, key, vars = {}) {
  const entry = text[key];
  if (!entry) return key;
  return String(entry[lang === "es" ? 1 : 0]).replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : ""));
}

